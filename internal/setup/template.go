func renderConfig(a answers) string {
	typ := "anthropic"
	if a.Kind == "openai" {
		typ = "openai"
	}
	search := a.Search
	if search == "" {
		search = "auto"
	}
	var users []string
	for _, id := range a.TGUsers {
		users = append(users, fmt.Sprint(id))
	}
	var b bytes.Buffer
	configTmpl.Execute(&b, map[string]any{
		"Date": time.Now().Format("2006-01-02 15:04"), "Type": typ, "BaseURL": a.BaseURL, "Auth": a.Auth,
		"Official": a.Kind == "official", "Smart": a.Smart, "Strong": a.Strong, "Cheap": a.Cheap,
		"Search": search, "Users": strings.Join(users, ", "),
	})
	return b.String()
}
